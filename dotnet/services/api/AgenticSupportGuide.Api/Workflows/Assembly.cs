using AgenticSupportGuide.Api.Agents.Shared;

namespace AgenticSupportGuide.Api.Workflows;

/// <summary>Turn validated agent outputs into the API response object.</summary>
public static class Assembly
{
    /// <summary>Merge the analyst's findings with the recommender's plan.</summary>
    public static Recommendation BuildRecommendation(
        DataAnalystOutput analysis,
        SupportRecommendationDraft draft,
        IReadOnlyList<ResourceRef> allowed,
        ValidatorReport report,
        string providerDisplay)
    {
        var byId = new Dictionary<string, ResourceRef>();
        foreach (var r in allowed)
        {
            byId[r.Id] = r;
        }
        var resourceMatches = draft.ResourceIds
            .Where(byId.ContainsKey)
            .Select(id => byId[id])
            .Select(r => new RecommendationResource(r.Id, r.Label, r.Kind))
            .ToList();
        return new Recommendation(
            DealerGroupId: draft.DealerGroupId,
            DetectedNeed: analysis.Analysis.DetectedNeed.Length > 0 ? analysis.Analysis.DetectedNeed : draft.DetectedNeed,
            EvidenceSummary: [.. analysis.Analysis.EvidenceBullets],
            Rationale: draft.Rationale,
            SupportTier: draft.SupportTier,
            RecommendedFrequency: draft.RecommendedFrequency,
            GroupingGuidance: draft.GroupingGuidance,
            ResourceMatches: resourceMatches,
            ManagerNextSteps: [.. draft.ManagerNextSteps],
            ProgressMonitoring: [.. draft.ProgressMonitoring],
            ReviewWindowDays: draft.ReviewWindowDays,
            DecisionRule: draft.DecisionRule,
            Caveats: [.. draft.Caveats],
            GoalSuggestions: [.. draft.GoalSuggestions],
            StrategySuggestions: [.. draft.StrategySuggestions],
            Citations: draft.Citations.Select(ToRecommendationCitation).ToList(),
            Completeness: new Dictionary<string, object> { ["ok"] = report.Passed, ["missing"] = report.IssueCodes.ToList() },
            HumanReviewState: HumanReview.PendingReview,
            GeneratedBy: $"Generated by three collaborating agents via {providerDisplay}.");
    }

    private static RecommendationCitation ToRecommendationCitation(Citation citation) =>
        new(
            citation.CitationId,
            citation.DealerGroupId,
            citation.SourceType,
            citation.SourceTitle,
            citation.SectionOrPage,
            citation.EvidenceSummary,
            citation.SourceRef,
            citation.RetrievedAt,
            citation.Confidence);
}
